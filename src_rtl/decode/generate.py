"""Generate fixed-geometry compute RTL from the simulator's selected profiles.

This is a compute-core generator, not an HBM controller or transformer compiler.
The manifest explicitly lists the interfaces still requiring system integration.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
MODEL=ROOT/'experiments/gemma3_1b_int8/hbm2/full_model'
sys.path.insert(0,str(MODEL))
from config import Architecture

PROFILES={'asic':'decode_asic_stream256','f2':'decode_f2_stream256'}

def outputs(platform):
    path=MODEL/'configs'/f'{PROFILES[platform]}.json'
    architecture=Architecture(**json.loads(path.read_text()))
    if architecture.dataflow!='os' or architecture.array_rows!=1:
        raise ValueError('Only one-row output-stationary arrays are implemented')
    p=architecture.array_partitions;c=architecture.array_cols
    # Keep one authoritative port contract. Fail if the core declaration changes.
    source=(HERE/'rtl/decode_os_core.sv').read_text()
    port_text=source.split(')(\n',1)[1].split('\n);',1)[0]
    port_text=port_text.replace('PARTITIONS',str(p)).replace('COLS',str(c)).replace('output reg','output wire')
    top=f'decode_{platform}_compute'
    wrapper=(f'// Generated by generate.py from {path.name}; do not edit.\n'
        f'// Compute subsystem only; see {top}.json for integration requirements.\n'
        f'module {top} (\n{port_text}\n);\n'
        f'    decode_os_core #(.PARTITIONS({p}), .COLS({c}), .MAX_M(4), .MAX_K(8192)) core (.*);\n'
        'endmodule\n')
    manifest=dict(top=top,scope='parallel INT8 compute core',configuration=architecture.to_dict(),
        physical_macs=p*c,core_register_bytes=dict(accumulators=p*c*4,activation_shift=p*c),
        model_memory=architecture.describe(),configuration_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
        required_integration=['Synchronous SRAM operand/partial-sum adapters and arbitration',
            'HBM DMA with 2048 outstanding requests and 32 pseudochannel interfaces',
            'FP32 vector/SFU and two-pass cache conversion with original rounding',
            'Full operator sequencer, clock-domain crossing and FPGA/ASIC implementation'])
    return {f'{top}.sv':wrapper,f'{top}.json':json.dumps(manifest,indent=2)+'\n'}

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    destination=HERE/'generated'
    if not args.check:destination.mkdir(exist_ok=True)
    for platform in PROFILES:
        for name,content in outputs(platform).items():
            path=destination/name
            if args.check:assert path.read_text()==content,f'Stale generated file: {path}'
            else:path.write_text(content)
    print('PASS generated compute profiles match simulator configurations')

if __name__=='__main__':main()
